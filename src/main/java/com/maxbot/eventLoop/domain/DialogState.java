package com.maxbot.eventLoop.domain;

/**
 * Состояние диалога. Хранится в колонке, а не в памяти, — иначе рестарт
 * контейнера оставляет пользователя в подвешенном состоянии.
 *
 * <p>Бот спрашивает два числа: сколько всего на карте и сколько из этого
 * на кино. Остальное — разница. Третий вопрос — откуда считать расстояние:
 * геолокация, точка кнопкой или «Пропустить».
 * Всё прочее делает мини-приложение.
 */
public enum DialogState {

    NEW,
    AWAITING_TOTAL,
    AWAITING_CINEMA,
    AWAITING_ORIGIN,
    READY
}
