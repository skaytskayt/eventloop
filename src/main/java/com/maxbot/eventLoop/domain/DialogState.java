package com.maxbot.eventLoop.domain;

/**
 * Состояние диалога. Хранится в колонке, а не в памяти, — иначе рестарт
 * контейнера оставляет пользователя в подвешенном состоянии.
 *
 * <p>Бот спрашивает два числа: сколько на кино и сколько на остальное.
 * Всё прочее делает мини-приложение.
 */
public enum DialogState {

    NEW,
    AWAITING_CINEMA,
    AWAITING_OTHER,
    READY
}
