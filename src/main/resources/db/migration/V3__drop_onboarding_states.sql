-- Бот больше не спрашивает район, расстояние, категории и даты: всё это
-- делает мини-приложение. Состояния под эти шаги удалены из DialogState.
--
-- Колонка dialog_state — VARCHAR, поэтому строка «AWAITING_CATEGORIES»
-- переживёт деплой и упадёт уже при чтении пользователя: enum такого
-- значения не знает. Ловится это не на старте, а на первом сообщении
-- конкретного человека — то есть на демо.
--
-- Кто был посреди старого онбординга, начинает с вопроса про баланс.
-- Кто дошёл до READY — остаётся в READY: баланс у него уже есть.
UPDATE app_user
SET dialog_state = 'AWAITING_BALANCE'
WHERE dialog_state NOT IN ('NEW', 'AWAITING_BALANCE', 'READY');
