-- V6 убрал таблицы реакций, пока не было кода, который в них пишет. Теперь он
-- есть: Mini App, открытый в MAX, присылает действия с подписанным initData,
-- и лайки, отложенное, дизлайки и покупки живут на сервере под MAX user id.
--
-- Внешних ключей нет намеренно. event_id — это eventId из app/data.js, а не
-- event_item.id: лента Mini App собрана из собственного датасета. max_user_id —
-- пользователь MAX, который мог открыть приложение из меню, ни разу не написав
-- боту, поэтому строки в app_user у него может и не быть.

-- Текущее состояние: одна строка на пару «пользователь — событие».
CREATE TABLE miniapp_reaction (
    max_user_id BIGINT      NOT NULL,
    event_id    INTEGER     NOT NULL CHECK (event_id > 0),
    kind        VARCHAR(16) NOT NULL CHECK (kind IN ('LIKED', 'SAVED', 'DISLIKED', 'BOUGHT')),
    price_rub   INTEGER     NOT NULL CHECK (price_rub BETWEEN 0 AND 100000),
    category    VARCHAR(32),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (max_user_id, event_id)
);

-- Журнал всех действий, включая просмотры и переходы к покупке, — из него
-- строится воронка на /stats.
CREATE TABLE miniapp_action (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    max_user_id BIGINT      NOT NULL,
    event_id    INTEGER     NOT NULL,
    action      VARCHAR(20) NOT NULL,
    price_rub   INTEGER     NOT NULL,
    category    VARCHAR(32),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX miniapp_action_action_idx ON miniapp_action (action);
