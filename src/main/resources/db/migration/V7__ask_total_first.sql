-- Бот теперь спрашивает сначала общий баланс карты, потом сколько из него на
-- кино. Состояние AWAITING_OTHER удалено, появилось AWAITING_TOTAL, а
-- AWAITING_CINEMA теперь значит «общую сумму уже назвал».
--
-- Строка «AWAITING_OTHER» пережила бы деплой и упала при чтении пользователя.
-- Кто был посреди старого разговора, начинает с общей суммы. Кто дошёл до
-- READY, там и остаётся: суммы у него уже записаны.
UPDATE app_user
SET dialog_state = 'AWAITING_TOTAL'
WHERE dialog_state NOT IN ('NEW', 'READY');
